/** 与本站分类信息可能相关的词（命中则不当成纯闲聊） */
const SITE_HINT =
  /租|房|招聘|二手|工作|卖|买|职位|薪资|简历|转让|商家|黄页|店铺|转租|合租|找工|全职|兼职|月租|搬家|家具|求购|出租|找房|招工|应聘|面试|求职|店面|服务员|驾照|工签|月嫂|保姆|装修|仓库|司机|招|主播|直播|带货|保洁|收银|洛杉矶|纽约|尔湾|旧金山|西雅图|休斯顿|芝加哥|波士顿|迈阿密|拉斯维加斯|凤凰城|圣地亚哥|达拉斯|奥斯汀|丹佛|亚特兰大/i

export type AiChatGuardResult = 'ok' | 'blocked' | 'offtopic'

function matchesBlockedPhrase(text: string): boolean {
  return BLOCKED_PHRASES.some((p) => text.includes(p))
}

function hasSiteHint(text: string): boolean {
  return SITE_HINT.test(text)
}

/** 纯语气/无实质内容（极短） */
function isMeaninglessNoise(text: string): boolean {
  const t = text.trim()
  if (t.length > 12) return false
  return /^[嗯嗯哦哦啊啊哈嘻呵呀哇额呃]+[。.!！?？\s]*$/u.test(t)
}

function isOffTopicSmalltalk(text: string): boolean {
  const t = text.trim()
  if (!t || hasSiteHint(t)) return false
  if (matchesBlockedPhrase(t)) return false

  const lower = t.toLowerCase()
  if (OFFTOPIC_KEYWORDS.some((k) => lower.includes(k.toLowerCase()))) {
    if (t.length <= 220) return true
    return false
  }

  if (t.length > 100) return false

  if (CHITCHAT_GREETING_RES.some((re) => re.test(t))) return true

  if (isMeaninglessNoise(t)) return true

  return false
}

export function classifyAiUserMessage(text: string): AiChatGuardResult {
  const t = text.trim()
  if (!t) return 'ok'
  if (matchesBlockedPhrase(t)) return 'blocked'
  if (isOffTopicSmalltalk(t)) return 'offtopic'
  return 'ok'
}
